import { ControlModel, DiscretizedMatrices } from '../types/control';

export interface GeneratedCodeBundle {
  cHeader: string;
  cSource: string;
  rustLib: string;
  hilHeader: string;
}

function fmtFloatC(v: number): string {
  const clean = Math.abs(v) < 1e-12 ? 0 : v;
  return `${clean.toPrecision(8)}f`;
}

function fmtFloatRust(v: number): string {
  const clean = Math.abs(v) < 1e-12 ? 0 : v;
  const s = clean.toPrecision(8);
  return s.includes('.') || s.includes('e') ? `${s}` : `${s}.0`;
}

function fmtMatC(mat: number[][], indent = '    '): string {
  return mat
    .map((row) => `${indent}{ ${row.map(fmtFloatC).join(', ')} }`)
    .join(',\n');
}

function fmtMatRust(mat: number[][], indent = '    '): string {
  return mat
    .map((row) => `${indent}[ ${row.map(fmtFloatRust).join(', ')} ]`)
    .join(',\n');
}

export function generateEmbeddedCode(
  model: ControlModel,
  discrete: DiscretizedMatrices
): GeneratedCodeBundle {
  const n = model.plant.n;
  const m = model.plant.m;
  const p = model.plant.p;
  const safeGuardId = model.id.toUpperCase().replace(/[^A-Z0-9_]/g, '_') || 'CUSTOM';
  const guard = `OPENLOOP_${safeGuardId}_CTRL_H`;
  const dtStr = model.baseDt.toString();

  const cHeader = `/**
 * @file ctrl_model.h
 * @brief Zero-allocation C99 fixed-step controller & discrete state-space plant
 *        Generated by OpenLoop (${model.license} License)
 *        Model: ${model.name} | dt = ${dtStr} s | Method: ${discrete.method.toUpperCase()}
 */
#ifndef ${guard}
#define ${guard}

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>

#ifdef __cplusplus
extern "C" {
#endif

#define CTRL_STATE_DIM   (${n}U)
#define CTRL_INPUT_DIM   (${m}U)
#define CTRL_OUTPUT_DIM  (${p}U)
#define CTRL_DT_SEC      (${fmtFloatC(model.baseDt)})

typedef struct {
    float x[CTRL_STATE_DIM];          /* Plant / observer state vector */
    float y[CTRL_OUTPUT_DIM];         /* Measured or modeled outputs   */
    float pid_integral;               /* Anti-windup integrator state  */
    float pid_deriv;                  /* Filtered derivative state     */
    float pid_prev_err;               /* Previous sample error         */
    float prev_u;                     /* Rate-limiter state            */
    uint32_t tick_count;              /* Deterministic sample counter  */
    bool saturated;                   /* Actuator clamp active flag    */
    bool watchdog_fault;              /* HIL safe-clamp fault latch    */
} CtrlState;

typedef struct {
    float ref;                        /* Reference setpoint            */
    float meas_state[CTRL_STATE_DIM]; /* Full-state feedback vector    */
    bool hil_rx_valid;                /* False triggers watchdog check */
} CtrlInput;

typedef struct {
    float u_cmd;                      /* Clamped actuator command      */
    float u_raw;                      /* Pre-saturation command        */
    float y_est[CTRL_OUTPUT_DIM];     /* Output vector                 */
    bool saturated;                   /* Clamp indicator               */
} CtrlOutput;

void ctrl_init(CtrlState *state);
void ctrl_step(CtrlState *state, const CtrlInput *in, CtrlOutput *out);
void ctrl_plant_step(CtrlState *state, float u_applied);
void ctrl_plant_step_mimo(CtrlState *state, const float u_vec[CTRL_INPUT_DIM]);

#ifdef __cplusplus
}
#endif

#endif /* ${guard} */
`;

  const cSource = `/**
 * @file ctrl_model.c
 * @brief Deterministic fixed-step C99 implementation (no heap, MISRA-friendly)
 */
#include "ctrl_model.h"

/* Discretized state-space matrices (${discrete.method.toUpperCase()}, dt = ${dtStr}s) */
static const float CTRL_AD[CTRL_STATE_DIM][CTRL_STATE_DIM] = {
${fmtMatC(discrete.Ad)}
};

static const float CTRL_BD[CTRL_STATE_DIM][CTRL_INPUT_DIM] = {
${fmtMatC(discrete.Bd)}
};

static const float CTRL_CD[CTRL_OUTPUT_DIM][CTRL_STATE_DIM] = {
${fmtMatC(discrete.Cd)}
};

static const float CTRL_DD[CTRL_OUTPUT_DIM][CTRL_INPUT_DIM] = {
${fmtMatC(discrete.Dd)}
};

static const float CTRL_LQR_K[CTRL_STATE_DIM] = {
    ${model.lqrK.map(fmtFloatC).join(', ')}
};

static const float CTRL_X0[CTRL_STATE_DIM] = {
    ${model.plant.x0.map(fmtFloatC).join(', ')}
};

/* Controller parameters */
static const float PID_KP      = ${fmtFloatC(model.pid.kp)};
static const float PID_KI      = ${fmtFloatC(model.pid.ki)};
static const float PID_KD      = ${fmtFloatC(model.pid.kd)};
static const float PID_N       = ${fmtFloatC(model.pid.nFilter)};
static const float PID_KB      = ${fmtFloatC(model.pid.kbAntiWindup)};
static const float SAT_MIN     = ${fmtFloatC(model.limits.satMin)};
static const float SAT_MAX     = ${fmtFloatC(model.limits.satMax)};
static const float RATE_LIMIT  = ${fmtFloatC(model.limits.rateLimit)};
static const float SAFE_CLAMP  = ${fmtFloatC(model.hil.safeClampValue)};

static inline float clampf(float v, float lo, float hi) {
    if (v < lo) return lo;
    if (v > hi) return hi;
    return v;
}

void ctrl_init(CtrlState *state) {
    if (state == NULL) { return; }
    for (size_t i = 0U; i < CTRL_STATE_DIM; ++i) {
        state->x[i] = CTRL_X0[i];
    }
    for (size_t i = 0U; i < CTRL_OUTPUT_DIM; ++i) {
        float acc = 0.0f;
        for (size_t j = 0U; j < CTRL_STATE_DIM; ++j) {
            acc += CTRL_CD[i][j] * state->x[j];
        }
        state->y[i] = acc;
    }
    state->pid_integral   = 0.0f;
    state->pid_deriv      = 0.0f;
    state->pid_prev_err   = 0.0f;
    state->prev_u         = 0.0f;
    state->tick_count     = 0U;
    state->saturated      = false;
    state->watchdog_fault = false;
}

void ctrl_step(CtrlState *state, const CtrlInput *in, CtrlOutput *out) {
    if ((state == NULL) || (in == NULL) || (out == NULL)) { return; }

    if (!in->hil_rx_valid) {
        state->watchdog_fault = true;
        out->u_raw = SAFE_CLAMP;
        out->u_cmd = SAFE_CLAMP;
        out->saturated = true;
        state->prev_u = SAFE_CLAMP;
        state->tick_count += 1U;
        return;
    }

    /* 1. Output projection y = Cd * x */
    float y_curr[CTRL_OUTPUT_DIM];
    for (size_t i = 0U; i < CTRL_OUTPUT_DIM; ++i) {
        float sum = 0.0f;
        for (size_t j = 0U; j < CTRL_STATE_DIM; ++j) {
            sum += CTRL_CD[i][j] * in->meas_state[j];
        }
        y_curr[i] = sum;
        state->y[i] = sum;
        out->y_est[i] = sum;
    }

    /* 2. Full-state LQR feedback */
    float u_lqr = 0.0f;
    for (size_t i = 0U; i < CTRL_STATE_DIM; ++i) {
        float target = (${model.lqrTracksRefOnState0 ? 'i == 0U' : 'false'}) ? in->ref : 0.0f;
        u_lqr += -CTRL_LQR_K[i] * (in->meas_state[i] - target);
    }

    /* 3. PID with derivative low-pass filter & back-calculation anti-windup */
    float u_pid = 0.0f;
    float err = 0.0f;
#if ${model.pid.enabled ? 1 : 0}
    const float pid_target = (${model.pid.tracksStepRef ? 'true' : 'false'}) ? in->ref : 0.0f;
    err = pid_target - y_curr[${model.pid.targetOutputIndex}U];
    const float alpha = (PID_N * CTRL_DT_SEC) / (1.0f + PID_N * CTRL_DT_SEC);
    const float raw_deriv = (err - state->pid_prev_err) / CTRL_DT_SEC;
    state->pid_deriv += alpha * (raw_deriv - state->pid_deriv);
    u_pid = (PID_KP * err) + (PID_KI * state->pid_integral) + (PID_KD * state->pid_deriv);
    state->pid_prev_err = err;
#endif

    const float u_raw = u_lqr + u_pid;

    /* 4. Rate limiter + actuator saturation */
    const float max_delta = RATE_LIMIT * CTRL_DT_SEC;
    const float u_rate = clampf(u_raw, state->prev_u - max_delta, state->prev_u + max_delta);
    const float u_sat = clampf(u_rate, SAT_MIN, SAT_MAX);
    const bool is_sat = (u_sat != u_rate);

#if ${model.pid.enabled ? 1 : 0}
    if (PID_KI != 0.0f) {
        const float aw = PID_KB * (u_sat - u_raw);
        state->pid_integral += (err + (aw / PID_KI)) * CTRL_DT_SEC;
    }
#endif

    state->prev_u = u_sat;
    state->saturated = is_sat;
    state->tick_count += 1U;

    out->u_raw = u_raw;
    out->u_cmd = u_sat;
    out->saturated = is_sat;
}

void ctrl_plant_step_mimo(CtrlState *state, const float u_vec[CTRL_INPUT_DIM]) {
    if ((state == NULL) || (u_vec == NULL)) { return; }
    float x_next[CTRL_STATE_DIM];
    for (size_t i = 0U; i < CTRL_STATE_DIM; ++i) {
        float acc = 0.0f;
        for (size_t k = 0U; k < CTRL_INPUT_DIM; ++k) {
            acc += CTRL_BD[i][k] * u_vec[k];
        }
        for (size_t j = 0U; j < CTRL_STATE_DIM; ++j) {
            acc += CTRL_AD[i][j] * state->x[j];
        }
        x_next[i] = acc;
    }
    for (size_t i = 0U; i < CTRL_STATE_DIM; ++i) {
        state->x[i] = x_next[i];
    }
    for (size_t i = 0U; i < CTRL_OUTPUT_DIM; ++i) {
        float acc = 0.0f;
        for (size_t k = 0U; k < CTRL_INPUT_DIM; ++k) {
            acc += CTRL_DD[i][k] * u_vec[k];
        }
        for (size_t j = 0U; j < CTRL_STATE_DIM; ++j) {
            acc += CTRL_CD[i][j] * state->x[j];
        }
        state->y[i] = acc;
    }
}

void ctrl_plant_step(CtrlState *state, float u_applied) {
    float u_vec[CTRL_INPUT_DIM] = { 0.0f };
    u_vec[0] = u_applied;
    ctrl_plant_step_mimo(state, u_vec);
}
`;

  const rustLib = `//! OpenLoop Embedded Controller Crate (Zero-Allocation \`#![no_std]\`)
//! License: ${model.license}
//! Model: ${model.name} | dt = ${dtStr}s | Method: ${discrete.method.toUpperCase()}

#![no_std]

pub const STATE_DIM: usize = ${n};
pub const INPUT_DIM: usize = ${m};
pub const OUTPUT_DIM: usize = ${p};
pub const DT_SEC: f32 = ${fmtFloatRust(model.baseDt)};

const AD: [[f32; STATE_DIM]; STATE_DIM] = [
${fmtMatRust(discrete.Ad)}
];

const BD: [[f32; INPUT_DIM]; STATE_DIM] = [
${fmtMatRust(discrete.Bd)}
];

const CD: [[f32; STATE_DIM]; OUTPUT_DIM] = [
${fmtMatRust(discrete.Cd)}
];

const DD: [[f32; INPUT_DIM]; OUTPUT_DIM] = [
${fmtMatRust(discrete.Dd)}
];

const LQR_K: [f32; STATE_DIM] = [ ${model.lqrK.map(fmtFloatRust).join(', ')} ];
const X0: [f32; STATE_DIM] = [ ${model.plant.x0.map(fmtFloatRust).join(', ')} ];

const PID_ENABLED: bool = ${model.pid.enabled};
const PID_TRACKS_REF: bool = ${model.pid.tracksStepRef};
const PID_TARGET_IDX: usize = ${model.pid.targetOutputIndex};
const PID_KP: f32 = ${fmtFloatRust(model.pid.kp)};
const PID_KI: f32 = ${fmtFloatRust(model.pid.ki)};
const PID_KD: f32 = ${fmtFloatRust(model.pid.kd)};
const PID_N: f32 = ${fmtFloatRust(model.pid.nFilter)};
const PID_KB: f32 = ${fmtFloatRust(model.pid.kbAntiWindup)};

const SAT_MIN: f32 = ${fmtFloatRust(model.limits.satMin)};
const SAT_MAX: f32 = ${fmtFloatRust(model.limits.satMax)};
const RATE_LIMIT: f32 = ${fmtFloatRust(model.limits.rateLimit)};
const SAFE_CLAMP: f32 = ${fmtFloatRust(model.hil.safeClampValue)};

#[repr(C)]
#[derive(Copy, Clone, Debug)]
pub struct CtrlState {
    pub x: [f32; STATE_DIM],
    pub y: [f32; OUTPUT_DIM],
    pub pid_integral: f32,
    pub pid_deriv: f32,
    pub pid_prev_err: f32,
    pub prev_u: f32,
    pub tick_count: u32,
    pub saturated: bool,
    pub watchdog_fault: bool,
}

#[repr(C)]
#[derive(Copy, Clone, Debug)]
pub struct CtrlOutput {
    pub u_cmd: f32,
    pub u_raw: f32,
    pub y_est: [f32; OUTPUT_DIM],
    pub saturated: bool,
}

#[inline(always)]
fn clamp_f32(v: f32, lo: f32, hi: f32) -> f32 {
    if v < lo { lo } else if v > hi { hi } else { v }
}

impl CtrlState {
    pub const fn new() -> Self {
        Self {
            x: X0,
            y: [0.0; OUTPUT_DIM],
            pid_integral: 0.0,
            pid_deriv: 0.0,
            pid_prev_err: 0.0,
            prev_u: 0.0,
            tick_count: 0,
            saturated: false,
            watchdog_fault: false,
        }
    }

    pub fn init(&mut self) {
        *self = Self::new();
        for i in 0..OUTPUT_DIM {
            let mut acc = 0.0;
            for j in 0..STATE_DIM {
                acc += CD[i][j] * self.x[j];
            }
            self.y[i] = acc;
        }
    }

    pub fn step(
        &mut self,
        ref_val: f32,
        meas_state: &[f32; STATE_DIM],
        hil_rx_valid: bool,
    ) -> CtrlOutput {
        if !hil_rx_valid {
            self.watchdog_fault = true;
            self.prev_u = SAFE_CLAMP;
            self.tick_count = self.tick_count.wrapping_add(1);
            return CtrlOutput {
                u_cmd: SAFE_CLAMP,
                u_raw: SAFE_CLAMP,
                y_est: self.y,
                saturated: true,
            };
        }

        let mut y_curr = [0.0_f32; OUTPUT_DIM];
        for i in 0..OUTPUT_DIM {
            let mut acc = 0.0;
            for j in 0..STATE_DIM {
                acc += CD[i][j] * meas_state[j];
            }
            y_curr[i] = acc;
            self.y[i] = acc;
        }

        let mut u_lqr = 0.0_f32;
        for i in 0..STATE_DIM {
            let target = if ${model.lqrTracksRefOnState0} && i == 0 { ref_val } else { 0.0 };
            u_lqr += -LQR_K[i] * (meas_state[i] - target);
        }

        let mut u_pid = 0.0_f32;
        let mut err = 0.0_f32;
        if PID_ENABLED {
            let pid_target = if PID_TRACKS_REF { ref_val } else { 0.0 };
            err = pid_target - y_curr[PID_TARGET_IDX];
            let alpha = (PID_N * DT_SEC) / (1.0 + PID_N * DT_SEC);
            let raw_deriv = (err - self.pid_prev_err) / DT_SEC;
            self.pid_deriv += alpha * (raw_deriv - self.pid_deriv);
            u_pid = (PID_KP * err) + (PID_KI * self.pid_integral) + (PID_KD * self.pid_deriv);
            self.pid_prev_err = err;
        }

        let u_raw = u_lqr + u_pid;
        let max_delta = RATE_LIMIT * DT_SEC;
        let u_rate = clamp_f32(u_raw, self.prev_u - max_delta, self.prev_u + max_delta);
        let u_sat = clamp_f32(u_rate, SAT_MIN, SAT_MAX);
        let saturated = (u_sat - u_rate) != 0.0;

        if PID_ENABLED && PID_KI != 0.0 {
            let aw = PID_KB * (u_sat - u_raw);
            self.pid_integral += (err + (aw / PID_KI)) * DT_SEC;
        }

        self.prev_u = u_sat;
        self.saturated = saturated;
        self.tick_count = self.tick_count.wrapping_add(1);

        CtrlOutput {
            u_cmd: u_sat,
            u_raw,
            y_est: y_curr,
            saturated,
        }
    }

    pub fn step_plant_sil_mimo(&mut self, u_vec: &[f32; INPUT_DIM]) {
        let mut x_next = [0.0_f32; STATE_DIM];
        for i in 0..STATE_DIM {
            let mut acc = 0.0_f32;
            for k in 0..INPUT_DIM {
                acc += BD[i][k] * u_vec[k];
            }
            for j in 0..STATE_DIM {
                acc += AD[i][j] * self.x[j];
            }
            x_next[i] = acc;
        }
        self.x = x_next;
        for i in 0..OUTPUT_DIM {
            let mut acc = 0.0_f32;
            for k in 0..INPUT_DIM {
                acc += DD[i][k] * u_vec[k];
            }
            for j in 0..STATE_DIM {
                acc += CD[i][j] * self.x[j];
            }
            self.y[i] = acc;
        }
    }

    pub fn step_plant_sil(&mut self, u_applied: f32) {
        let mut u_vec = [0.0_f32; INPUT_DIM];
        u_vec[0] = u_applied;
        self.step_plant_sil_mimo(&u_vec);
    }
}
`;

  const hilHeader = `/**
 * @file hil_frame.h
 * @brief Deterministic HIL binary framing (COBS + CRC16-CCITT)
 */
#ifndef OPENLOOP_HIL_FRAME_H
#define OPENLOOP_HIL_FRAME_H

#include <stdint.h>
#include <stddef.h>

typedef struct __attribute__((packed)) {
    uint16_t sof;          /* 0xAA55 */
    uint32_t seq;          /* Monotonic packet sequence */
    uint32_t tick_us;      /* Target microsecond timestamp */
    float    signals[4];   /* [ref, y0, y1, u_cmd] */
    uint16_t crc16;        /* CRC-16-CCITT (poly 0x1021) */
} HilWireFrame;

static inline uint16_t hil_crc16_ccitt(const uint8_t *data, size_t len) {
    uint16_t crc = 0xFFFFU;
    for (size_t i = 0; i < len; ++i) {
        crc ^= (uint16_t)data[i] << 8U;
        for (uint8_t b = 0; b < 8U; ++b) {
            crc = (crc & 0x8000U) ? (uint16_t)((crc << 1U) ^ 0x1021U) : (uint16_t)(crc << 1U);
        }
    }
    return crc;
}

static inline size_t hil_cobs_encode(const uint8_t *in, size_t len, uint8_t *out) {
    size_t read_idx = 0U, write_idx = 1U, code_idx = 0U;
    uint8_t code = 1U;
    while (read_idx < len) {
        if (in[read_idx] == 0U) {
            out[code_idx] = code;
            code = 1U;
            code_idx = write_idx++;
            read_idx++;
        } else {
            out[write_idx++] = in[read_idx++];
            code++;
            if (code == 0xFFU) {
                out[code_idx] = code;
                code = 1U;
                code_idx = write_idx++;
            }
        }
    }
    out[code_idx] = code;
    out[write_idx++] = 0x00U; /* Frame delimiter */
    return write_idx;
}

#endif /* OPENLOOP_HIL_FRAME_H */
`;

  return {
    cHeader,
    cSource,
    rustLib,
    hilHeader,
  };
}
